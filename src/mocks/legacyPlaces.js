// Simple colored placeholder photo (the real ones come from the server).
function photo(label, hue, index) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="668" height="324" viewBox="0 0 668 324"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="hsl(${hue} 55% ${78 - index * 6}%)"/><stop offset="1" stop-color="hsl(${(hue + 30) % 360} 45% ${48 - index * 4}%)"/></linearGradient></defs><rect width="668" height="324" fill="url(#g)"/><text x="50%" y="50%" dominant-baseline="middle" text-anchor="middle" font-family="sans-serif" font-weight="700" font-size="34" fill="#fff">${label}</text><text x="50%" y="64%" dominant-baseline="middle" text-anchor="middle" font-family="sans-serif" font-size="20" fill="#fff" opacity="0.8">photo ${index + 1}</text></svg>`
  return `data:image/svg+xml,${encodeURIComponent(svg)}`
}

function photos(label, hue, count) {
  return Array.from({ length: count }, (_, i) => photo(label, hue, i))
}

